An established business has an advantage here: the process already exists. The job is to see it clearly.

## The whiteboard test: AI problem or process problem?

Here's the test in full. Can you write down how your business works from the customer's point of view?

- Where your leads and traffic come from
- How a lead becomes a customer
- What happens once they've said yes, through to delivering the work
- What keeps them coming back

If you can't map those stages and the steps inside them, you don't have an AI automation problem yet. You have a business system and process problem, and no tool will fix that for you.

If you're an established Australian business, this generally won't be you. You got to where you are for a reason, and the systems exist. They might not be written down as SOPs. You might just have a handful of people who know how to get things done. That's got you this far, but it doesn't scale well with AI, because AI can't work from what's only in someone's head.

## How to map your business processes for automation

This is the method I use with clients. It's business process mapping, organised around the customer journey, from how clients find you to what keeps them coming back.

![A customer journey map in four stages: acquisition and reach, sales and proposals, delivery, and retention and business health. Each stage lists the human tasks under it, with writing proposals and quotes highlighted as the first to automate. Below, each task is ranked by hours, cost and impact to form the automation roadmap.](/blog/business-process-automation-ai-or-process/customer-journey-map.png)

1. **Acquisition and reach.** How do you get clients, and where do they come from? Referrals, Google, ads, an outside agency.
2. **Sales and proposals.** What does your funnel look like right now? How do you create proposals and quotes? Where are you winning, and where do things get stuck?
3. **Delivery.** How do you deliver your product or service? This is usually where the most time goes, so break it into every part that takes someone's time.
4. **Retention and business health.** Everything around the work itself: keeping clients, admin, reporting, and the marketing that keeps the business growing.

Under each stage, write down the tasks people do today. Then mark the ones you'd love off your plate, and be honest about the ones that eat hours every week.

You'll end up with a page of tasks. That page is more useful than any list of "10 things to automate with AI", because it's your business.

## How to decide what to automate first

Now rank them. For each task, work out how many hours it takes, what those hours cost, and the potential impact of doing it faster or better. Those numbers give you a roadmap: what to go after, and in what order. It's the same ranking that goes into the report after our [free 1-hour session](#book-a-free-1-hour-session).

Then tackle them one at a time. Building one good automation takes evaluation, testing and iteration. It's doable, and we've had great success with it, but it's not the one-shot job people think it is. That's especially true for an established business, where the work has to hold up to the standard your customers already expect.

## What it looks like in practice: proposals at Compass

Compass is a buyers' agency we work with. When we looked at their sales stage, proposals stood out.

The team were already using [Claude](https://claude.com) to write them, and each one still took up to 2 hours. The hard part was customising each proposal and pulling in the right past acquisitions.

So we built a proposal-writing skill based on what a good Compass proposal looks like, and connected it to their previous acquisitions and their website. When a potential buyer sends a brief, it finds acquisitions that match that exact brief, which shows the buyer Compass has already done what they're asking for. We're also connecting it to their reviews, so it can pick the ones that fit the brief too.

![How the Compass proposal skill works: the buyer's brief goes into a proposal-writing skill that draws on past acquisitions, the website and reviews, and produces a tailored draft the team finishes. Time per proposal went from up to 2 hours to about 30 minutes.](/blog/business-process-automation-ai-or-process/compass-proposal-workflow.png)

Proposals now take about half an hour, and they're better.

That's the reality of AI. People expect the time to go to zero, and it doesn't. The team still spends 30 minutes on each one, but they save an hour and a half every time, and over a year that adds up to a lot. That's only the time saved. It doesn't count what the team does with that hour and a half instead.

We took a process that already won them business and made it faster and better, without adding a single new system.

## When to look at new AI growth systems

There's still a place for something new. Down the line it makes sense to look at growth systems: an automated sales outreach process, cold email, or something that helps with your SEO.

The problem is that people often start there. Start inside the business, automate the processes that already work, get the time back, and then look at growth.

## Key takeaways

**What is business process automation?** Using software, now often AI, to handle the repeatable steps in how your business wins and serves customers, with a person still checking the output where it matters.

**What should you automate first?** A process you already run well that takes a lot of hours. Map your customer journey, list the tasks under each stage, then rank them by hours, cost and impact.

**Do you need documented SOPs first?** Not to start. You do need to be able to map the stages and the tasks inside them, and for many businesses that map becomes their first real SOP.

**Will AI take a task down to zero?** Rarely. At Compass, proposals went from up to 2 hours to about 30 minutes, and they got better. The saving comes from doing the work faster with a person still involved.

**Should you start with AI for sales outreach or marketing?** Usually not. Get your existing processes working with AI first, then look at growth once you know what your customers respond to.

