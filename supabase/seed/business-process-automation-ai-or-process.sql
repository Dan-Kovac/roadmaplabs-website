## Where most businesses go wrong with AI

The businesses I work with are excited about AI, and fair enough. They've seen what people are doing with it on social media, and they've seen what competitors are doing. So they go looking for new places to use it, often in parts of the business that have never needed it.

I've seen the results: elaborate dashboards, and vibe-coded apps and tools that look really cool but don't work in reality. When I walk into a business and see a few of these, it's usually a sign they're on the wrong track.

New use cases pull attention away from the processes that make the business money today. Those processes already work. They're just manual, and they run on people, which is exactly what makes them worth automating.

## I made the same mistake with Review Buddy

I've done this myself.

Review Buddy is one of our internal companies, and it's new, so we didn't have established processes. I started building automations anyway. One of the first was a sales and outreach process: cold email to a set number of potential customers every day.

